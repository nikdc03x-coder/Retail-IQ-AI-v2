"""
RetailIQ AI V2 — Business Analytics Aggregations Module

Computes rigorous hierarchical aggregations:
1. Department-week sales
2. Store-week sales (primary unit of store operations and forecasting)
3. Total network weekly sales
4. Store and Department rankings
5. Store-type efficiency metrics
6. Holiday dynamics and seasonal indices
"""

from typing import Any
import numpy as np
import pandas as pd

from src.retailiq.config import REPORT_SUBDIRS, ensure_directories
from src.retailiq.data.loader import load_analytical_dataset


def assign_holiday_name(row_or_series: pd.Series | pd.DataFrame) -> pd.Series:
    """Label Walmart holiday weeks with specific business event names.

    Holidays identified:
    - Super Bowl: February (approx week 6)
    - Labor Day: September (approx week 36)
    - Thanksgiving: November (approx week 47)
    - Christmas: Late December (approx week 52)
    """
    is_holiday = row_or_series["IsHoliday"]
    month = row_or_series["Date"].dt.month

    conditions = [
        (~is_holiday),
        (is_holiday & (month == 2)),
        (is_holiday & (month == 9)),
        (is_holiday & (month == 11)),
        (is_holiday & (month == 12)),
    ]
    choices = [
        "Non-Holiday",
        "Super Bowl",
        "Labor Day",
        "Thanksgiving",
        "Christmas",
    ]
    return pd.Series(np.select(conditions, choices, default="Other Holiday"), index=row_or_series.index)


def aggregate_store_week_sales(df: pd.DataFrame) -> pd.DataFrame:
    """Aggregate department-level transactions to Store-Week level.

    This represents total weekly revenue generated by an entire store location,
    which serves as the primary business intelligence and forecasting target.

    Args:
        df: Analytical DataFrame (department-week level).

    Returns:
        DataFrame aggregated at (Store, Date) level.
    """
    store_week = (
        df.groupby(["Store", "Date", "Type", "Size", "IsHoliday", "Year", "Month", "WeekOfYear"], observed=True)
        .agg(
            Weekly_Sales=("Weekly_Sales", "sum"),
            Active_Departments=("Dept", "nunique"),
            Temperature=("Temperature", "first"),
            Fuel_Price=("Fuel_Price", "first"),
            CPI=("CPI", "first"),
            Unemployment=("Unemployment", "first"),
            MarkDown1=("MarkDown1", "first"),
            MarkDown2=("MarkDown2", "first"),
            MarkDown3=("MarkDown3", "first"),
            MarkDown4=("MarkDown4", "first"),
            MarkDown5=("MarkDown5", "first"),
        )
        .reset_index()
    )

    store_week["Weekly_Sales"] = store_week["Weekly_Sales"].round(2)
    store_week["Holiday_Name"] = assign_holiday_name(store_week)
    return store_week.sort_values(by=["Store", "Date"]).reset_index(drop=True)


def aggregate_weekly_network_sales(store_week_df: pd.DataFrame) -> pd.DataFrame:
    """Aggregate across all stores to compute total network weekly sales.

    Args:
        store_week_df: Store-week aggregated DataFrame.

    Returns:
        DataFrame at Date level with network total and average metrics.
    """
    network_weekly = (
        store_week_df.groupby(["Date", "IsHoliday", "Holiday_Name", "Year", "Month", "WeekOfYear"], observed=True)
        .agg(
            Total_Network_Sales=("Weekly_Sales", "sum"),
            Active_Stores=("Store", "nunique"),
            Mean_Store_Sales=("Weekly_Sales", "mean"),
            Median_Store_Sales=("Weekly_Sales", "median"),
            Min_Store_Sales=("Weekly_Sales", "min"),
            Max_Store_Sales=("Weekly_Sales", "max"),
        )
        .reset_index()
    )

    network_weekly["Total_Network_Sales"] = network_weekly["Total_Network_Sales"].round(2)
    network_weekly["Mean_Store_Sales"] = network_weekly["Mean_Store_Sales"].round(2)
    network_weekly["Median_Store_Sales"] = network_weekly["Median_Store_Sales"].round(2)
    return network_weekly.sort_values(by="Date").reset_index(drop=True)


def aggregate_store_performance(store_week_df: pd.DataFrame) -> pd.DataFrame:
    """Compute store-level revenue rankings and space productivity metrics.

    Args:
        store_week_df: Store-week aggregated DataFrame.

    Returns:
        DataFrame with Store rankings and metrics.
    """
    store_perf = (
        store_week_df.groupby(["Store", "Type", "Size"], observed=True)
        .agg(
            Total_Sales=("Weekly_Sales", "sum"),
            Recorded_Weeks=("Date", "count"),
            Mean_Weekly_Sales=("Weekly_Sales", "mean"),
            Std_Weekly_Sales=("Weekly_Sales", "std"),
            Min_Weekly_Sales=("Weekly_Sales", "min"),
            Max_Weekly_Sales=("Weekly_Sales", "max"),
        )
        .reset_index()
    )

    total_network_sales = store_perf["Total_Sales"].sum()
    store_perf["Sales_Share_Pct"] = (store_perf["Total_Sales"] / total_network_sales * 100.0).round(2)
    store_perf["Sales_Per_SqFt"] = (store_perf["Total_Sales"] / store_perf["Size"]).round(2)
    store_perf["Weekly_Sales_Per_SqFt"] = (store_perf["Mean_Weekly_Sales"] / store_perf["Size"]).round(4)
    store_perf["Coefficient_Of_Variation"] = (store_perf["Std_Weekly_Sales"] / store_perf["Mean_Weekly_Sales"]).round(3)

    # Rank stores by total sales
    store_perf = store_perf.sort_values(by="Total_Sales", ascending=False).reset_index(drop=True)
    store_perf["Sales_Rank"] = range(1, len(store_perf) + 1)
    store_perf["Total_Sales"] = store_perf["Total_Sales"].round(2)
    store_perf["Mean_Weekly_Sales"] = store_perf["Mean_Weekly_Sales"].round(2)
    store_perf["Std_Weekly_Sales"] = store_perf["Std_Weekly_Sales"].round(2)

    return store_perf


def aggregate_department_performance(df: pd.DataFrame) -> pd.DataFrame:
    """Compute department revenue contributions and Pareto share across network.

    Args:
        df: Analytical DataFrame (department-week level).

    Returns:
        DataFrame with Department rankings and contribution metrics.
    """
    dept_perf = (
        df.groupby("Dept", observed=True)
        .agg(
            Total_Sales=("Weekly_Sales", "sum"),
            Observations=("Weekly_Sales", "count"),
            Active_Stores=("Store", "nunique"),
            Mean_Weekly_Sales=("Weekly_Sales", "mean"),
            Std_Weekly_Sales=("Weekly_Sales", "std"),
            Min_Sales=("Weekly_Sales", "min"),
            Max_Sales=("Weekly_Sales", "max"),
        )
        .reset_index()
    )

    total_sales = dept_perf["Total_Sales"].sum()
    dept_perf["Sales_Share_Pct"] = (dept_perf["Total_Sales"] / total_sales * 100.0).round(2)

    dept_perf = dept_perf.sort_values(by="Total_Sales", ascending=False).reset_index(drop=True)
    dept_perf["Cumulative_Share_Pct"] = dept_perf["Sales_Share_Pct"].cumsum().round(2)
    dept_perf["Dept_Rank"] = range(1, len(dept_perf) + 1)

    dept_perf["Total_Sales"] = dept_perf["Total_Sales"].round(2)
    dept_perf["Mean_Weekly_Sales"] = dept_perf["Mean_Weekly_Sales"].round(2)
    dept_perf["Std_Weekly_Sales"] = dept_perf["Std_Weekly_Sales"].round(2)

    return dept_perf


def aggregate_store_type_performance(store_perf_df: pd.DataFrame) -> pd.DataFrame:
    """Compare performance across Store Types (A, B, C).

    Args:
        store_perf_df: Output of aggregate_store_performance.

    Returns:
        DataFrame summarizing Type A, B, and C characteristics.
    """
    type_perf = (
        store_perf_df.groupby("Type", observed=True)
        .agg(
            Store_Count=("Store", "count"),
            Total_Sales=("Total_Sales", "sum"),
            Mean_Store_Sales=("Total_Sales", "mean"),
            Mean_Weekly_Store_Sales=("Mean_Weekly_Sales", "mean"),
            Mean_Store_Size=("Size", "mean"),
            Median_Store_Size=("Size", "median"),
        )
        .reset_index()
    )

    total_network = type_perf["Total_Sales"].sum()
    type_perf["Network_Sales_Share_Pct"] = (type_perf["Total_Sales"] / total_network * 100.0).round(2)
    type_perf["Sales_Per_SqFt"] = (type_perf["Total_Sales"] / (type_perf["Mean_Store_Size"] * type_perf["Store_Count"])).round(2)

    type_perf["Total_Sales"] = type_perf["Total_Sales"].round(2)
    type_perf["Mean_Store_Sales"] = type_perf["Mean_Store_Sales"].round(2)
    type_perf["Mean_Weekly_Store_Sales"] = type_perf["Mean_Weekly_Store_Sales"].round(2)
    type_perf["Mean_Store_Size"] = type_perf["Mean_Store_Size"].round(0)

    return type_perf.sort_values(by="Total_Sales", ascending=False).reset_index(drop=True)


def aggregate_holiday_dynamics(store_week_df: pd.DataFrame) -> pd.DataFrame:
    """Calculate sales lift and revenue impact across specific holidays.

    Compares average store-week sales during non-holiday weeks vs:
    - All holiday weeks combined
    - Super Bowl
    - Labor Day
    - Thanksgiving
    - Christmas

    Args:
        store_week_df: Store-week aggregated DataFrame.

    Returns:
        DataFrame with holiday lift percentages and metrics.
    """
    # Non-holiday baseline
    non_holiday = store_week_df[~store_week_df["IsHoliday"]]
    base_mean = non_holiday["Weekly_Sales"].mean()
    base_median = non_holiday["Weekly_Sales"].median()

    # Individual holiday groups
    holiday_summary = (
        store_week_df[store_week_df["IsHoliday"]]
        .groupby("Holiday_Name", observed=True)
        .agg(
            Recorded_Weeks=("Date", "nunique"),
            Total_Sales=("Weekly_Sales", "sum"),
            Mean_Store_Weekly_Sales=("Weekly_Sales", "mean"),
            Median_Store_Weekly_Sales=("Weekly_Sales", "median"),
        )
        .reset_index()
    )

    # Combined holiday row
    all_holiday = store_week_df[store_week_df["IsHoliday"]]
    combined_row = pd.DataFrame([{
        "Holiday_Name": "All Holidays Combined",
        "Recorded_Weeks": all_holiday["Date"].nunique(),
        "Total_Sales": all_holiday["Weekly_Sales"].sum(),
        "Mean_Store_Weekly_Sales": all_holiday["Weekly_Sales"].mean(),
        "Median_Store_Weekly_Sales": all_holiday["Weekly_Sales"].median(),
    }])

    # Baseline non-holiday row
    baseline_row = pd.DataFrame([{
        "Holiday_Name": "Non-Holiday Baseline",
        "Recorded_Weeks": non_holiday["Date"].nunique(),
        "Total_Sales": non_holiday["Weekly_Sales"].sum(),
        "Mean_Store_Weekly_Sales": base_mean,
        "Median_Store_Weekly_Sales": base_median,
    }])

    holiday_df = pd.concat([baseline_row, combined_row, holiday_summary], ignore_index=True)

    # Calculate lift % relative to baseline
    holiday_df["Lift_Vs_Baseline_Pct"] = (
        (holiday_df["Mean_Store_Weekly_Sales"] - base_mean) / base_mean * 100.0
    ).round(2)

    holiday_df["Total_Sales"] = holiday_df["Total_Sales"].round(2)
    holiday_df["Mean_Store_Weekly_Sales"] = holiday_df["Mean_Store_Weekly_Sales"].round(2)
    holiday_df["Median_Store_Weekly_Sales"] = holiday_df["Median_Store_Weekly_Sales"].round(2)

    return holiday_df


def aggregate_monthly_seasonality(network_weekly_df: pd.DataFrame) -> pd.DataFrame:
    """Analyze monthly seasonality across recorded years.

    Args:
        network_weekly_df: Network-level weekly sales DataFrame.

    Returns:
        DataFrame summarizing monthly average sales and seasonal indices.
    """
    month_names = {
        1: "January", 2: "February", 3: "March", 4: "April",
        5: "May", 6: "June", 7: "July", 8: "August",
        9: "September", 10: "October", 11: "November", 12: "December",
    }

    monthly = (
        network_weekly_df.groupby("Month", observed=True)
        .agg(
            Recorded_Weeks=("Date", "count"),
            Total_Sales=("Total_Network_Sales", "sum"),
            Mean_Weekly_Sales=("Total_Network_Sales", "mean"),
            Min_Weekly_Sales=("Total_Network_Sales", "min"),
            Max_Weekly_Sales=("Total_Network_Sales", "max"),
        )
        .reset_index()
    )

    monthly["Month_Name"] = monthly["Month"].map(month_names)
    overall_mean = network_weekly_df["Total_Network_Sales"].mean()
    monthly["Seasonal_Index"] = (monthly["Mean_Weekly_Sales"] / overall_mean).round(3)
    monthly["Lift_Vs_Average_Pct"] = ((monthly["Mean_Weekly_Sales"] - overall_mean) / overall_mean * 100.0).round(2)

    monthly["Total_Sales"] = monthly["Total_Sales"].round(2)
    monthly["Mean_Weekly_Sales"] = monthly["Mean_Weekly_Sales"].round(2)
    monthly["Min_Weekly_Sales"] = monthly["Min_Weekly_Sales"].round(2)
    monthly["Max_Weekly_Sales"] = monthly["Max_Weekly_Sales"].round(2)

    ordered_cols = [
        "Month", "Month_Name", "Recorded_Weeks", "Total_Sales",
        "Mean_Weekly_Sales", "Seasonal_Index", "Lift_Vs_Average_Pct",
        "Min_Weekly_Sales", "Max_Weekly_Sales",
    ]
    return monthly[ordered_cols].sort_values(by="Month").reset_index(drop=True)


def run_business_analytics(
    df: pd.DataFrame | None = None,
    save_reports: bool = True,
) -> dict[str, Any]:
    """Execute complete business intelligence aggregation suite and export reports.

    Args:
        df: Optional pre-loaded analytical DataFrame.
        save_reports: Whether to save CSV reports to reports/business_analytics/.

    Returns:
        Dictionary of all aggregated DataFrames.
    """
    ensure_directories()
    data = df if df is not None else load_analytical_dataset()

    # 1. Store-Week aggregation
    store_week_df = aggregate_store_week_sales(data)

    # 2. Network weekly sales
    network_weekly_df = aggregate_weekly_network_sales(store_week_df)

    # 3. Store rankings & productivity
    store_perf_df = aggregate_store_performance(store_week_df)

    # 4. Department rankings & contribution
    dept_perf_df = aggregate_department_performance(data)

    # 5. Store type comparisons
    store_type_df = aggregate_store_type_performance(store_perf_df)

    # 6. Holiday dynamics & lifts
    holiday_df = aggregate_holiday_dynamics(store_week_df)

    # 7. Monthly seasonality
    monthly_df = aggregate_monthly_seasonality(network_weekly_df)

    out_dir = REPORT_SUBDIRS["business_analytics"]

    if save_reports:
        network_weekly_df.to_csv(out_dir / "01_weekly_sales.csv", index=False)
        store_perf_df.to_csv(out_dir / "02_store_performance.csv", index=False)
        dept_perf_df.to_csv(out_dir / "03_department_performance.csv", index=False)
        store_week_df.to_csv(out_dir / "04_store_week_sales.csv", index=False)
        holiday_df.to_csv(out_dir / "05_holiday_comparison.csv", index=False)
        store_type_df.to_csv(out_dir / "06_store_type_performance.csv", index=False)
        monthly_df.to_csv(out_dir / "07_monthly_seasonality.csv", index=False)

    return {
        "network_weekly": network_weekly_df,
        "store_performance": store_perf_df,
        "department_performance": dept_perf_df,
        "store_week": store_week_df,
        "holiday_comparison": holiday_df,
        "store_type": store_type_df,
        "monthly_seasonality": monthly_df,
    }
